    /**
     * Handles planet selection change events.
     * Updates gravity, image, and info text based on selected planet.
     *
     * @param evt The ActionEvent triggered when a new planet is selected
     */
    private void planetSelectorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_planetSelectorActionPerformed
        // TODO add your handling code here:

        String planet = (String) planetSelector.getSelectedItem();

        lblGravity.setVisible(false);
        txtGravity.setVisible(false);

        // Normal green: [51,204,0]
        btnGo.setBackground(new java.awt.Color(0, 204, 204));

        //Set the icon to the label
        switch (planet) {
            case "Sun":
                planetGravity = 274.0;
                lblPlanetInfo.setText("Sun is the center of our solar system.");
                imagePath = "Sun.jpg";
                break;
            case "Mercury":
                planetGravity = 3.7;
                lblPlanetInfo.setText("Mercury is the closest planet to the Sun.");
                imagePath = "Mercury.jpg";
                break;
            case "Venus":
                planetGravity = 8.87;
                lblPlanetInfo.setText("Venus has a thick, toxic atmosphere.");
                imagePath = "Venus.jpg";
                break;
            case "Moon":
                planetGravity = 1.62;
                lblPlanetInfo.setText("Moon is the Earth's satellite.");
                imagePath = "Moon.jpg";
                break;
            case "Earth":
                planetGravity = 9.81;
                lblPlanetInfo.setText("Earth is the only planet known to support life.");
                imagePath = "Earth.jpg";
                break;
            case "Mars":
                planetGravity = 3.71;
                lblPlanetInfo.setText("Mars is known as the Red Planet.");
                imagePath = "Mars.jpg";
                break;
            case "Jupiter":
                planetGravity = 24.79;
                lblPlanetInfo.setText("Jupiter is the largest planet in our solar system.");
                imagePath = "Jupiter.jpg";
                break;
            case "Saturn":
                planetGravity = 10.44;
                lblPlanetInfo.setText("Saturn is famous for its beautiful rings.");
                imagePath = "Saturn.jpg";
                break;
            case "Uranus":
                planetGravity = 8.69;
                lblPlanetInfo.setText("Uranus rotates on its side.");
                imagePath = "Uranus.jpg";
                break;
            case "Neptune":
                planetGravity = 11.15;
                lblPlanetInfo.setText("Neptune has strong winds and storms.");
                imagePath = "Neptune.jpg";
                break;
            case "Other":
                lblGravity.setVisible(true);
                txtGravity.setVisible(true);
                lblPlanetInfo.setText("Please enter gravity for the selected object.");
                break;
            default:
                lblPlanetInfo.setText("Not a recognized planet or solar body.");
                break;
        }

        planetDisplay.setIcon(new javax.swing.ImageIcon(getClass().getResource("/images/" + imagePath)));


    }//GEN-LAST:event_planetSelectorActionPerformed

    /**
     * Called when the "GO" button is pressed.
     * Calculates the user's weight on the selected planet or object.
     *
     * @param evt The ActionEvent triggered by the button
     */
    private void btnGoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGoActionPerformed
        // TODO add your handling code here:

        try {
            String planet = (String) planetSelector.getSelectedItem();

            if (txtMass.getText().trim().isEmpty() || planetGravity == 0) {
                JOptionPane.showMessageDialog(Space_Interface.this, "Fields cannot be blank and Gravity cannot be 0");
            } else {

                btnGo.setBackground(new java.awt.Color(51, 204, 0));

                if ("Other".equals(planet)) {

                    double gravityD = Double.parseDouble(txtGravity.getText());

                    planetGravity = gravityD;
                }

                double weightOfYou = Double.parseDouble(txtMass.getText());

                // earthWeightLbs * (planetGravity / EARTH_GRAVITY);
                double weightOnPlanet = weightOfYou * (planetGravity / EARTH_GRAVITY);

                weightOnPlanet = Math.round(weightOnPlanet * 100.0) / 100.0; // round to 2 decimals

                txtAnswer.setText("You weigh " + weightOnPlanet + " pounds on " + planet);
            }
        } catch (NumberFormatException e) {
            // In case of invalid input (non-numeric)
            txtAnswer.setText("Invalid input: No Letters");
        }

    }//GEN-LAST:event_btnGoActionPerformed

