    private void convertValues() {

        for (int index = 0; index < grade.size(); index++) {

            if (grade.get(index).equalsIgnoreCase("A+")) {
                gradeVal.add(4.0);
            } else if (grade.get(index).equalsIgnoreCase("A")) {
                gradeVal.add(3.7);
            } else if (grade.get(index).equalsIgnoreCase("A-")) {
                gradeVal.add(3.5);
            } else if (grade.get(index).equalsIgnoreCase("B+")) {
                gradeVal.add(3.3);
            } else if (grade.get(index).equalsIgnoreCase("B")) {
                gradeVal.add(3.0);
            } else if (grade.get(index).equalsIgnoreCase("B-")) {
                gradeVal.add(2.7);
            } else if (grade.get(index).equalsIgnoreCase("C+")) {
                gradeVal.add(2.3);
            } else if (grade.get(index).equalsIgnoreCase("C")) {
                gradeVal.add(2.0);
            } else if (grade.get(index).equalsIgnoreCase("C-")) {
                gradeVal.add(1.7);
            } else if (grade.get(index).equalsIgnoreCase("D+")) {
                gradeVal.add(1.3);
            } else if (grade.get(index).equalsIgnoreCase("D")) {
                gradeVal.add(1.0);
            } else if (grade.get(index).equalsIgnoreCase("F")) {
                gradeVal.add(0.0);
            } else {
                // Handle unexpected input
                System.out.println("Invalid grade entered: " + grade.get(index));

            }
        }
        // Convert each String to Integer
        for (String s : credit) {
            creditInt.add(Integer.valueOf(s));
        }

    }

    private void calculateGPA() {
        double totalQualityPoints = 0;
        double totalCredits = 0;

        for (int i = 0; i < gradeVal.size(); i++) {
            totalQualityPoints += gradeVal.get(i) * creditInt.get(i);
            totalCredits += creditInt.get(i);
        }

        double gpa = totalQualityPoints / totalCredits;
        String gpaString = "Your GPA is: "+ gpa;
        System.out.printf("Your GPA is: %.2f%n", gpa);
        
        Display.setText(gpaString);
    }
