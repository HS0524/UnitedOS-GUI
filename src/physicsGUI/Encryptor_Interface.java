    /**
     * Decrypts the encrypted text input using AES and displays the result.
     *
     * @param evt the ActionEvent triggered by the Decrypt button
     */
    private void btnDecryptActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDecryptActionPerformed
        //EncryptionUtils encryptionUtils = new EncryptionUtils();
        SecretKey secretKey;

        String value1 = txtDecrypt.getText();
        //String value2 = txtDecrypt.getText();

        try {
            System.out.println("entered try");

            secretKey = EncryptionUtils.loadKey(); // Load the stored AES key

            String decryptedText = EncryptionUtils.decrypt(value1, secretKey);

            txtEncrypt.setText(decryptedText);
            System.out.println("entered 2");

            System.out.println("exit try");
        } catch (Exception ex) {
            Logger.getLogger(Encryptor_Interface.class.getName()).log(Level.SEVERE, null, ex);
        }

    }//GEN-LAST:event_btnDecryptActionPerformed

