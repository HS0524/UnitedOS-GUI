    /**
     * Encrypts and saves the entered username and password to a file. Marks the
     * account as either admin or standard based on the flag.
     *
     * @param Admin true if the account is an admin account, false otherwise
     */
    private void encryptAccount(boolean Admin) {
        String txtUser = txtLogin.getText();
        String newPassword = new String(txtPasswordSecured.getPassword()); // Use getPassword()
        String admin = "Admin.false";
        int style = 1; // sets look and feel

        if (!txtUser.isBlank() && !newPassword.isBlank() && !txtUser.equalsIgnoreCase(" Enter Username") && !newPassword.equalsIgnoreCase(" Enter Password")) {
            txtLogin.setBackground(txtPasswordSecured.getBackground());
            if (Admin == true) {
                admin = "Admin.true";
                btnGiveAdmin.setText("Registered as Admin");
            } else if (Admin == false) {
                btnCreateAcc.setText("Registered as Standard");
            }

            try {

                SecretKey secretKey = EncryptionUtils.loadKey(); // Load the stored AES key

                String encryptedLogin = EncryptionUtils.encrypt(txtUser, secretKey);
                String encryptedPassword = EncryptionUtils.encrypt(newPassword, secretKey);
                String encryptedAdmin = EncryptionUtils.encrypt(admin, secretKey);
                // No need to encrypt style

                try (FileWriter fw = new FileWriter(fileNameEncrypted, true); BufferedWriter bw = new BufferedWriter(fw); PrintWriter pw = new PrintWriter(bw)) {

                    pw.println(encryptedLogin + ";" + encryptedPassword + ";" + encryptedAdmin + ";" + style);
                    System.out.println("Account encrypted successfully.");
                }

                try (FileWriter fw = new FileWriter(fileName, true); BufferedWriter bw = new BufferedWriter(fw); PrintWriter pw = new PrintWriter(bw)) {

                    if (saveKey == true) {

                        pw.println(txtUser + ";" + newPassword + ";" + admin + ";" + style);
                        System.out.println("Account saved successfully.");
                    }
                }

                title.setText("You may now close this page");
                btnCreateAcc.setForeground(new java.awt.Color(0, 0, 0)); // set text to black

                this.dispose();
                JOptionPane.showMessageDialog(null, "Account Created Successfully");

            } catch (Exception ex) {
                //Logger.getLogger(CreateAccount_Interface.class.getName()).log(Level.SEVERE, null, ex);
            }
        } else if (txtUser.isBlank() || newPassword.isBlank() || txtUser.equalsIgnoreCase(" Enter Username") || newPassword.equalsIgnoreCase(" Enter Password")) {
            txtLogin.setBackground(new java.awt.Color(255, 204, 204)); // set text to light red
            txtPasswordSecured.setBackground(new java.awt.Color(255, 204, 204)); // set text to light red

            JOptionPane.showMessageDialog(null, "Fields cannot be blank");
        }
    }

