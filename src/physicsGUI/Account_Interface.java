    /**
     * Called when "Make Admin" button is clicked. Prompts for access code to
     * elevate user privileges.
     */
    private void btnMakeAdminActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMakeAdminActionPerformed
        // TODO add your handling code here:

        String adminCode = "BlueSky24";

        if (txtNewUser.getText().trim().isEmpty() || txtNewPassword.getText().trim().isEmpty()) {
            // Fields are empty
            JOptionPane.showMessageDialog(Account_Interface.this, "Update Failed: Fields cannot be blank");
            return;
        }
        String inputText = JOptionPane.showInputDialog(null, "Enter access code:", "Input Dialog", JOptionPane.PLAIN_MESSAGE);

        if (inputText != null && !inputText.trim().isEmpty() && inputText.equals(adminCode)) {

            updateUserAccount(userInherited, passwordInherited, fileNameEncrypted, ";", adminAccessInherited,
                    true // (true = make Admin.true)
            );

            homePage.logout();

        } else if (!inputText.trim().isEmpty() && !inputText.equals(passwordInherited)) {
            // Code entered but incorrect
            JOptionPane.showMessageDialog(null, "Incorrect Code");
        } else {
            JOptionPane.showMessageDialog(Account_Interface.this, "Update Failed: Field cannot be blank");
        }
    }//GEN-LAST:event_btnMakeAdminActionPerformed

