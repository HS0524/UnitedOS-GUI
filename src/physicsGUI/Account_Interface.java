    /**
     * Updates a user account: 1. Removes the old user credentials from
     * encrypted file 2. Adds updated credentials (encrypted + plaintext) 3.
     * Preserves all other accounts exactly as they were
     *
     * @param username current username to remove
     * @param password current password to remove
     * @param filepath encrypted file path
     * @param delimiter delimiter such as ";"
     * @param adminAccess old admin flag (not needed)
     * @param isAdmin whether new account should be admin
     */
    public void updateUserAccount(String username, String password, String filepath,
            String delimiter, String adminAccess, boolean isAdmin) {

        String newUser = txtNewUser.getText().trim();
        String newPass = new String(txtNewPassword.getPassword()).trim();
        String adminFlag = isAdmin ? "Admin.true" : "Admin.false";

        List<String> encryptedLines = new ArrayList<>();
        EncryptionUtils encryptionUtils = new EncryptionUtils();
        String currentLine;

        try {
            SecretKey secretKey = EncryptionUtils.loadKey();

            // 1. Scan AES encrypted file and remove target credentials, keeping other intact
            try (BufferedReader bReader = new BufferedReader(new FileReader(filepath))) {

                while ((currentLine = bReader.readLine()) != null) {
                    String[] data = currentLine.split(delimiter);
                    if (data.length < 2) {
                        encryptedLines.add(currentLine);
                        continue;
                    }

                    String decUser = EncryptionUtils.decrypt(data[0], secretKey);
                    String decPass = EncryptionUtils.decrypt(data[1], secretKey);

                    // Skip ONLY the matching user (removing old account)
                    if (decUser.equals(username) && decPass.equals(password)) {
                        System.out.println("Old account removed.");
                        continue;
                    }

                    // Keep account intact
                    encryptedLines.add(currentLine);
                }
            }

            // 2. write new updated encrypted credentials
            String encU = EncryptionUtils.encrypt(newUser, secretKey);
            String encP = EncryptionUtils.encrypt(newPass, secretKey);
            String encA = EncryptionUtils.encrypt(adminFlag, secretKey);

            if (adminAccess.equalsIgnoreCase("Delete")) {
                encU = "";  // blank out fields
                encP = "";
                encA = "";
            }
            
            encryptedLines.add(encU + delimiter + encP + delimiter + encA);

            try (BufferedWriter writer = new BufferedWriter(new FileWriter(filepath, false))) {
                for (String line : encryptedLines) {
                    writer.write(line);
                    writer.newLine();
                }
            }

            // 3. Rewrite plaintext file
            try (BufferedWriter writer = new BufferedWriter(new FileWriter(fileName, false))) {

                for (String encryptedLine : encryptedLines) {
                    String[] data = encryptedLine.split(delimiter);

                    String decU = EncryptionUtils.decrypt(data[0], secretKey);
                    String decP = EncryptionUtils.decrypt(data[1], secretKey);
                    String decA = EncryptionUtils.decrypt(data[2], secretKey);

                    writer.write(decU + delimiter + decP + delimiter + decA);
                    writer.newLine();
                }
            }

            // confirmation message on UI
            btnUpdate.setText(isAdmin ? "Admin Granted" : "Registered"); // confirm on UI
            btnMakeAdmin.setText(isAdmin ? "Admin Granted" : "Registered"); // confirm on UI

            System.out.println("Account updated successfully.");

        } catch (Exception e) {
            System.out.println("Error in updateUserAccount: " + e.getMessage());
        }
    }


