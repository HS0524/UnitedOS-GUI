    /**
     * Evaluates the calculator's supported arithmetic expression.
     *
     * @param expression expression containing numeric values and arithmetic
     *                   operators
     * @return the calculated numeric result
     */
    public double calculateEquation(String expression) {
        expression = expression.replaceAll("\\s+", "");

        double result = 0;
        char operator = '+';
        String number = "";

        for (int i = 0; i < expression.length(); i++) {
            char c = expression.charAt(i);

            // Number (digit or decimal)
            if (Character.isDigit(c) || c == '.') {
                number += c;
            } // Operator
            else if ("+-*/".indexOf(c) != -1) {

                // Error: two operators in a row (e.g. "+-")
                if (number.isEmpty()) {
                    throw new IllegalArgumentException(
                            "Invalid operator sequence at position " + i
                    );
                }

                double value = Double.parseDouble(number);

                switch (operator) {
                    case '+':
                        result += value;
                        break;
                    case '-':
                        result -= value;
                        break;
                    case '*':
                        result *= value;
                        break;
                    case '/':
                        result /= value;
                        break;
                }

                operator = c;
                number = "";
            } // Invalid character
            else {
                throw new IllegalArgumentException(
                        "Invalid character '" + c + "' at position " + i
                );
            }
        }

        // Apply last number
        if (number.isEmpty()) {
            throw new IllegalArgumentException("Expression ends with an operator");
        }

        double value = Double.parseDouble(number);
        switch (operator) {
            case '+':
                result += value;
                break;
            case '-':
                result -= value;
                break;
            case '*':
                result *= value;
                break;
            case '/':
                result /= value;
                break;
        }

        return result;
    }


